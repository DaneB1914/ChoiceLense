import { FullDecisionAnalysis } from '../types/decision';

export function formatDecisionAsMarkdown(analysis: FullDecisionAnalysis): string {
  const { input, prosAndCons, comparison, swots, blindSpots, recommendation } = analysis;

  let md = `# ChoiceLens Decision Analysis: ${input.title}\n\n`;
  md += `**Date:** ${new Date(analysis.createdAt).toLocaleDateString()} · **Decision Class:** ${recommendation.decisionClass}\n\n`;

  if (input.context) {
    md += `## Context & Background\n${input.context}\n\n`;
  }

  md += `## Executive Recommendation\n`;
  md += `> **Primary Verdict:** ${recommendation.primaryVerdict}\n`;
  md += `> **Confidence Level:** ${recommendation.confidenceScore}%\n\n`;
  md += `### Rationale\n${recommendation.rationale}\n\n`;
  md += `### When to Reconsider Alternative\n${recommendation.whenToPickAlternative}\n\n`;
  md += `### Reversal & Pivot Plan\n${recommendation.reversalPlan}\n\n`;

  md += `## Key Action Plan\n`;
  recommendation.actionPlan.forEach((step) => {
    md += `- [${step.completed ? 'x' : ' '}] **Step ${step.stepNumber}** (${step.timeframe}): ${step.task}\n`;
  });
  md += `\n`;

  md += `## Pros & Cons Breakdown\n`;
  prosAndCons.forEach((item) => {
    md += `### ${item.optionTitle} (Net Score: ${item.netScore > 0 ? '+' : ''}${item.netScore})\n`;
    md += `*${item.summary}*\n\n`;
    md += `**Pros:**\n`;
    item.pros.forEach((p) => {
      md += `- **[+${p.score}] ${p.title}** (${p.category} | Impact: ${p.impact}): ${p.explanation}\n`;
    });
    md += `\n**Cons:**\n`;
    item.cons.forEach((c) => {
      md += `- **[${c.score}] ${c.title}** (${c.category} | Impact: ${c.impact}): ${c.explanation}\n`;
      md += `  *Mitigation:* ${c.mitigation}\n`;
    });
    md += `\n`;
  });

  md += `## Criteria Comparison Matrix\n\n`;
  const options = input.options;
  md += `| Criterion | Weight | ${options.join(' | ')} |\n`;
  md += `| --- | --- | ${options.map(() => '---').join(' | ')} |\n`;
  comparison.matrix.forEach((row) => {
    const currentWeight =
      analysis.customWeights?.[row.criteriaId] ??
      comparison.criteria.find((c) => c.id === row.criteriaId)?.weight ??
      5;
    const scores = options.map((opt) => `${row.scores?.[opt] ?? '-'}/10`);
    md += `| ${row.criteriaName} | ${currentWeight} | ${scores.join(' | ')} |\n`;
  });
  md += `\n`;

  md += `### Key Tradeoffs\n`;
  comparison.keyTradeoffs.forEach((t) => {
    md += `- ${t}\n`;
  });
  md += `\n`;

  md += `## SWOT Analysis\n\n`;
  swots.forEach((swot) => {
    md += `### ${swot.optionTitle}\n`;
    md += `- **Strengths:** ${swot.strengths.join('; ')}\n`;
    md += `- **Weaknesses:** ${swot.weaknesses.join('; ')}\n`;
    md += `- **Opportunities:** ${swot.opportunities.join('; ')}\n`;
    md += `- **Threats:** ${swot.threats.join('; ')}\n\n`;
  });

  md += `## Blind Spots & Cognitive Biases\n\n`;
  blindSpots.cognitiveBiases.forEach((b) => {
    md += `### ${b.bias}\n`;
    md += `- **Trap:** ${b.warning}\n`;
    md += `- **Reflection:** *${b.reflectionQuestion}*\n\n`;
  });

  md += `### Pre-Mortem Scenario\n`;
  md += `> ${blindSpots.preMortem.worstCaseScenario}\n\n`;
  md += `**Early Warning Indicators:**\n`;
  blindSpots.preMortem.warningSigns.forEach((sign) => {
    md += `- ${sign}\n`;
  });
  md += `\n**Prevention Tactics:**\n`;
  blindSpots.preMortem.preventionTactics.forEach((tactic) => {
    md += `- ${tactic}\n`;
  });
  md += `\n---\n*Generated by ChoiceLens Decision Intelligence*`;

  return md;
}
